// **어떤 변화가 이득인지 손해인지를 정하는 유일한 자리다.**
//
// 이 저장소는 같은 실수를 세 번 했다. 전부 "줄어들면 나쁘다" 로 판단한 것이다:
//
//   1. 룬 설명문을 /감소한다|사라진다/ 로 훑어 페널티를 만들었다 — 공허·다가옴+ 의 쿨감,
//      위엄의 받는 피해 감소, 무형의 이동 속도 감소 해제가 전부 페널티로 잡혔다
//   2. 유틸 항목의 색을 direction === '감소' 로 정했다 — 여신·녹슨 방패·맹세+ 의
//      「받는 피해 감소」가 손해로 빨갛게 나오고, 무형의 「받는 피해 30% 증가」는
//      손해인데 아무 표시도 안 났다
//   3. 1번을 고치면서 2번을 못 봤다. 같은 가정이 다른 파일 다른 줄에 남아 있었다
//
// 매번 **다른 파일 다른 줄**이었다는 것이 요점이다. 한 자리를 고쳐도 다음 사람이 옆에서
// 다시 만든다 — '감소' 라는 낱말이 손해처럼 읽히기 때문이다. 그래서 판단을 여기 하나로
// 모으고, 다른 파일에서 방향 낱말로 좋고 나쁨을 정하는 것을 테스트가 금지한다
// (`tests/limits.test.mjs` 의 「좋고 나쁨은 한 곳에서만 정한다」).
//
// 고쳐야 할 것이 생기면 여기와 `STAT_BETTER_WHEN`(데이터)만 보면 된다.
import { STAT_BETTER_WHEN } from './rune-conditionals.mjs';

/**
 * 이 변화가 손해인가.
 *
 * 방향만으로는 답이 안 나온다 — 무엇이 움직였는지를 함께 봐야 한다.
 * 받는 피해는 줄면 이득이고 늘면 손해다. 이동 속도는 반대다.
 *
 * 모르는 스탯은 **손해로 단정하지 않는다.** 없는 손해를 만드는 쪽이 놓치는 것보다 나쁘다 —
 * 위 1·2번이 전부 그 방향으로 틀렸다. 빠진 스탯은 검증기가 막으므로 여기서 추측하지 않는다.
 *
 * @param {string} stat 움직인 값의 이름. `STAT_BETTER_WHEN` 의 키여야 한다
 * @param {'증가'|'감소'} direction 그 값이 어느 쪽으로 움직였는가
 * @returns {boolean} 손해면 true
 */
export function isHarmful(stat, direction) {
  const better = STAT_BETTER_WHEN[stat];
  if (better === undefined) return false;
  return (direction === '증가') !== (better === '높을수록');
}
